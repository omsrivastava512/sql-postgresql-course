RESET ROLE;
DROP SCHEMA IF EXISTS course_code CASCADE;
DO $$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'course_code_owner') THEN CREATE ROLE course_code_owner NOLOGIN; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'course_code_worker') THEN CREATE ROLE course_code_worker NOLOGIN; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'course_code_alice') THEN CREATE ROLE course_code_alice NOLOGIN; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'course_code_bob') THEN CREATE ROLE course_code_bob NOLOGIN; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'course_code_outsider') THEN CREATE ROLE course_code_outsider NOLOGIN; END IF;
END $$;
CREATE SCHEMA course_code AUTHORIZATION course_code_owner;
CREATE TABLE course_code.documents (id integer PRIMARY KEY, owner_role name NOT NULL, title text NOT NULL);
INSERT INTO course_code.documents VALUES (1, 'course_code_alice', 'Alice document'), (2, 'course_code_bob', 'Bob document');
ALTER TABLE course_code.documents OWNER TO course_code_owner;
ALTER TABLE course_code.documents ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_documents ON course_code.documents USING (owner_role = current_user);
CREATE TABLE course_code.labels (code integer PRIMARY KEY, label text NOT NULL);
INSERT INTO course_code.labels VALUES (1, 'Queued'), (2, 'Sent');
ALTER TABLE course_code.labels OWNER TO course_code_owner;
CREATE TABLE course_code.delivery_labels (code integer PRIMARY KEY, label text NOT NULL);
INSERT INTO course_code.delivery_labels VALUES (5, 'Collected'), (6, 'Delivered');
ALTER TABLE course_code.delivery_labels OWNER TO course_code_owner;
GRANT USAGE ON SCHEMA course_code TO course_code_worker, course_code_alice, course_code_bob, course_code_outsider;
GRANT SELECT ON course_code.documents TO course_code_worker, course_code_alice, course_code_bob;
GRANT SELECT ON course_code.labels, course_code.delivery_labels TO course_code_worker;
CREATE VIEW course_code.document_list AS SELECT id, title FROM course_code.documents;
ALTER VIEW course_code.document_list OWNER TO course_code_owner;
GRANT SELECT ON course_code.document_list TO course_code_alice, course_code_bob;
CREATE FUNCTION course_code.document_count() RETURNS integer LANGUAGE sql SECURITY DEFINER SET search_path = pg_catalog, course_code, pg_temp AS $$ SELECT count(*)::integer FROM course_code.documents $$;
ALTER FUNCTION course_code.document_count() OWNER TO course_code_owner;
CREATE FUNCTION course_code.worker_count() RETURNS integer LANGUAGE sql SECURITY DEFINER SET search_path = pg_catalog, course_code, pg_temp AS $$ SELECT count(*)::integer FROM course_code.documents $$;
ALTER FUNCTION course_code.worker_count() OWNER TO course_code_worker;
CREATE FUNCTION course_code.label_for(p_code integer) RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = course_code AS $$ BEGIN RETURN (SELECT label FROM labels WHERE code = p_code); END $$;
ALTER FUNCTION course_code.label_for(integer) OWNER TO course_code_worker;
